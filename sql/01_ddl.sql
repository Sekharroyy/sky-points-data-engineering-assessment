);

CREATE TABLE IF NOT EXISTS SKYPOINTS.CORE.COUNTRY_TARGET_CONFIG (
  COUNTRY_CODE          STRING NOT NULL,
  TARGET_TABLE          STRING NOT NULL,
  IS_ENABLED            BOOLEAN NOT NULL DEFAULT TRUE
);

MERGE INTO SKYPOINTS.CORE.COUNTRY_TARGET_CONFIG t
USING (
  SELECT column1::STRING AS COUNTRY_CODE, column2::STRING AS TARGET_TABLE
  FROM VALUES
    ('IND', 'MEMBERS_IND'),
    ('USA', 'MEMBERS_USA'),
    ('AUS', 'MEMBERS_AUS'),
    ('PHL', 'MEMBERS_PHL'),
    ('CAN', 'MEMBERS_CAN')
) s
ON t.COUNTRY_CODE = s.COUNTRY_CODE
WHEN MATCHED THEN UPDATE SET TARGET_TABLE = s.TARGET_TABLE, IS_ENABLED = TRUE
WHEN NOT MATCHED THEN INSERT (COUNTRY_CODE, TARGET_TABLE, IS_ENABLED)
  VALUES (s.COUNTRY_CODE, s.TARGET_TABLE, TRUE);

