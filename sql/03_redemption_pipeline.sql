-- Input: JSON Lines (one member object per line), one JSON object per file, or a
-- top-level array of member objects. Upload files under FEED_STAGE/REDEMPTIONS/.
-- No redemption JSON file was included with the local sample CSVs, so this pipeline
-- is provided but has not been demonstrated end-to-end with redemption rows.
USE DATABASE SKYPOINTS;
USE SCHEMA STG;

SET BATCH_ID = (SELECT UUID_STRING());

COPY INTO SKYPOINTS.RAW.REDEMPTION_LANDING
  (INGEST_BATCH_ID, SOURCE_FILE, SOURCE_ROW_NUMBER, RAW_RECORD)
FROM (
  SELECT $BATCH_ID::STRING, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER,
         $1
  FROM @SKYPOINTS.RAW.FEED_STAGE/REDEMPTIONS/
)
FILE_FORMAT = (FORMAT_NAME = SKYPOINTS.RAW.FF_REDEMPTION_JSON)
ON_ERROR = 'ABORT_STATEMENT';

-- Hashing is kept outside the restricted COPY transformation SELECT list.
UPDATE SKYPOINTS.RAW.REDEMPTION_LANDING
SET RECORD_HASH = SHA2(TO_JSON(RAW_RECORD), 256)
WHERE INGEST_BATCH_ID = $BATCH_ID::STRING;

CREATE OR REPLACE TEMPORARY TABLE BATCH_REDEMPTION_ROWS AS
WITH flattened AS (
  SELECT r.INGEST_BATCH_ID, r.SOURCE_FILE, r.SOURCE_ROW_NUMBER,
         r.INGESTED_AT, r.RAW_RECORD,
         r.RAW_RECORD:"member_id"::STRING AS PARTNER_MEMBER_ID,
         r.RAW_RECORD:"country_code"::STRING AS SOURCE_COUNTRY_CODE,
         TRY_TO_DATE(r.RAW_RECORD:"feed_date"::STRING, 'YYYYMMDD') AS FEED_DATE,
         x.VALUE AS RAW_TRANSACTION,
         x.VALUE:"txn_id"::STRING AS TXN_ID,
         x.VALUE:"partner"::STRING AS PARTNER_CODE,
         TRY_TO_DATE(x.VALUE:"txn_date"::STRING, 'YYYYMMDD') AS TXN_DATE,
         TRY_TO_NUMBER(x.VALUE:"miles_redeemed"::STRING, 18, 0) AS MILES_REDEEMED,
         UPPER(TRIM(x.VALUE:"status"::STRING)) AS STATUS
  FROM SKYPOINTS.RAW.REDEMPTION_LANDING r,
       LATERAL FLATTEN(INPUT => r.RAW_RECORD:"redemptions") x
  WHERE r.INGEST_BATCH_ID = $BATCH_ID::STRING
), resolved AS (
  SELECT f.*,
         mx.GLOBAL_MEMBER_ID AS MEMBER_KEY,
         ARRAY_CONSTRUCT_COMPACT(
           IFF(PARTNER_MEMBER_ID IS NULL OR TRIM(PARTNER_MEMBER_ID) = '', 'MISSING_MEMBER_ID', NULL),
           IFF(TXN_ID IS NULL OR TRIM(TXN_ID) = '', 'MISSING_TXN_ID', NULL),
           IFF(PARTNER_CODE IS NULL OR TRIM(PARTNER_CODE) = '', 'MISSING_PARTNER', NULL),
           IFF(FEED_DATE IS NULL, 'INVALID_FEED_DATE', NULL),
           IFF(TXN_DATE IS NULL, 'INVALID_TXN_DATE', NULL),
           IFF(MILES_REDEEMED IS NULL OR MILES_REDEEMED < 0, 'INVALID_MILES_REDEEMED', NULL),
           IFF(STATUS IS NULL OR STATUS = '', 'MISSING_STATUS', NULL),
           IFF(mx.GLOBAL_MEMBER_ID IS NULL, 'UNRESOLVED_GLOBAL_MEMBER_ID', NULL)
         ) AS DQ_ERRORS
  FROM flattened f
  -- Partner IDs must be mapped to the same canonical MEMBER_KEY used by member feeds.
  -- Populate this crosswalk from an authoritative partner identity mapping first.
  LEFT JOIN SKYPOINTS.CORE.MEMBER_ID_XREF mx
    ON mx.SOURCE_SYSTEM = 'PARTNER'
   AND mx.SOURCE_MEMBER_ID = f.PARTNER_MEMBER_ID
   AND (
     (f.SOURCE_COUNTRY_CODE IS NULL AND mx.SOURCE_COUNTRY_CODE IS NULL)
     OR mx.SOURCE_COUNTRY_CODE = f.SOURCE_COUNTRY_CODE
   )
   AND (mx.ACTIVE_FROM IS NULL OR mx.ACTIVE_FROM <= f.TXN_DATE)
   AND (mx.ACTIVE_TO IS NULL OR mx.ACTIVE_TO >= f.TXN_DATE)
)
SELECT *, ARRAY_SIZE(DQ_ERRORS) = 0 AS IS_VALID
FROM resolved;

INSERT INTO SKYPOINTS.RAW.REDEMPTION_DQ_QUARANTINE
  (INGEST_BATCH_ID, SOURCE_FILE, SOURCE_ROW_NUMBER, TXN_ID, DQ_ERRORS, RAW_RECORD)
SELECT INGEST_BATCH_ID, SOURCE_FILE, SOURCE_ROW_NUMBER, TXN_ID, DQ_ERRORS, RAW_RECORD
FROM BATCH_REDEMPTION_ROWS
WHERE NOT IS_VALID;

MERGE INTO SKYPOINTS.CORE.REDEMPTION_TRANSACTION t
USING (
  SELECT * FROM BATCH_REDEMPTION_ROWS
  WHERE IS_VALID
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY PARTNER_CODE, TXN_ID
    ORDER BY FEED_DATE DESC, INGESTED_AT DESC, SOURCE_FILE DESC, SOURCE_ROW_NUMBER DESC
  ) = 1
) s
  ON t.PARTNER_CODE = s.PARTNER_CODE AND t.TXN_ID = s.TXN_ID
WHEN MATCHED AND (s.FEED_DATE > t.FEED_DATE OR
                  (s.FEED_DATE = t.FEED_DATE AND s.INGESTED_AT >= t.INGESTED_AT)) THEN UPDATE SET
  t.MEMBER_KEY = s.MEMBER_KEY,
  t.PARTNER_MEMBER_ID = s.PARTNER_MEMBER_ID,
  t.FEED_DATE = s.FEED_DATE,
  t.TXN_DATE = s.TXN_DATE,
  t.MILES_REDEEMED = s.MILES_REDEEMED,
  t.STATUS = s.STATUS,
  t.SOURCE_FILE = s.SOURCE_FILE,
  t.SOURCE_ROW_NUMBER = s.SOURCE_ROW_NUMBER,
  t.INGESTED_AT = s.INGESTED_AT,
  t.RAW_TRANSACTION = s.RAW_TRANSACTION
WHEN NOT MATCHED THEN INSERT (
  PARTNER_CODE, TXN_ID, MEMBER_KEY, PARTNER_MEMBER_ID, FEED_DATE, TXN_DATE,
  MILES_REDEEMED, STATUS, SOURCE_FILE, SOURCE_ROW_NUMBER, INGESTED_AT, RAW_TRANSACTION
) VALUES (
  s.PARTNER_CODE, s.TXN_ID, s.MEMBER_KEY, s.PARTNER_MEMBER_ID, s.FEED_DATE,
  s.TXN_DATE, s.MILES_REDEEMED, s.STATUS, s.SOURCE_FILE, s.SOURCE_ROW_NUMBER,
  s.INGESTED_AT, s.RAW_TRANSACTION
);

-- Use the historical/as-of profile table when reporting the member's country at
-- transaction time. The current table answers only where the member is now.
SELECT t.TXN_ID, t.TXN_DATE, t.PARTNER_CODE, t.MILES_REDEEMED, t.STATUS,
       m.MEMBER_ID, m.MEMBER_NAME, m.COUNTRY_CODE AS CURRENT_COUNTRY_CODE
FROM SKYPOINTS.CORE.REDEMPTION_TRANSACTION t
JOIN SKYPOINTS.CORE.MEMBER_PROFILE_CURRENT m USING (MEMBER_KEY)
WHERE t.INGESTED_AT >= DATEADD(day, -1, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ);
