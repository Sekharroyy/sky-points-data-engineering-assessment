  SOURCE_SYSTEM         STRING NOT NULL,
  SOURCE_COUNTRY_CODE   STRING,
  SOURCE_MEMBER_ID      STRING NOT NULL,
  GLOBAL_MEMBER_ID      STRING NOT NULL,
  ACTIVE_FROM           DATE,
  ACTIVE_TO             DATE,
