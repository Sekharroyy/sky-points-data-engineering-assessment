-- Hashing and load-time expressions are deliberately outside COPY transformations.
UPDATE SKYPOINTS.RAW.MEMBER_LANDING
SET RECORD_HASH = SHA2(TO_JSON(RAW_RECORD), 256)
WHERE INGEST_BATCH_ID = $BATCH_ID::STRING;

-- Convert each source schema to canonical columns. TRY_TO_DATE preserves invalid
-- values as NULL so they can be quarantined with an explicit reason.
INSERT INTO SKYPOINTS.STG.MEMBER_NORMALIZED (
  INGEST_BATCH_ID, SOURCE_LAYOUT, MEMBER_KEY, MEMBER_ID, MEMBER_NAME, COUNTRY_CODE,
  SOURCE_COUNTRY_CODE, DATE_OF_BIRTH, TIER_CODE, ENROLLMENT_DATE,
  LAST_FLIGHT_DATE, ACCOUNT_TYPE, ACTIVE_MEMBER, AGENT_NAME, STATE_CODE,
  POST_CODE, AGE, STALE_MEMBER, RECORD_VERSION_TS, INGESTED_AT, SOURCE_FILE,
  SOURCE_ROW_NUMBER, RECORD_HASH, DQ_ERRORS, IS_VALID, RAW_RECORD
)
WITH extracted AS (
  SELECT r.*,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN RAW_RECORD:"Member_Id"::STRING
      WHEN 'IND_CSV' THEN RAW_RECORD:"ID"::STRING
      WHEN 'USA_CSV' THEN RAW_RECORD:"ID"::STRING
      WHEN 'AUS_CSV' THEN RAW_RECORD:"Unique ID"::STRING
    END AS MEMBER_ID_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN RAW_RECORD:"Member_Name"::STRING
      WHEN 'IND_CSV' THEN RAW_RECORD:"Name"::STRING
      WHEN 'USA_CSV' THEN RAW_RECORD:"Name"::STRING
      WHEN 'AUS_CSV' THEN RAW_RECORD:"Member Name"::STRING
    END AS MEMBER_NAME_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN RAW_RECORD:"DOB"::STRING
      WHEN 'IND_CSV' THEN RAW_RECORD:"DOB"::STRING
      WHEN 'USA_CSV' THEN NULL
      WHEN 'AUS_CSV' THEN RAW_RECORD:"Date of Birth"::STRING
    END AS DOB_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN RAW_RECORD:"Tier_Code"::STRING
      WHEN 'IND_CSV' THEN RAW_RECORD:"TierCode"::STRING
      WHEN 'USA_CSV' THEN RAW_RECORD:"TierCode"::STRING
      WHEN 'AUS_CSV' THEN RAW_RECORD:"Tier Type"::STRING
    END AS TIER_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN RAW_RECORD:"Enrollment_Date"::STRING
      WHEN 'IND_CSV' THEN RAW_RECORD:"EnrollmentDate"::STRING
      WHEN 'USA_CSV' THEN RAW_RECORD:"EnrollmentDate"::STRING
      WHEN 'AUS_CSV' THEN RAW_RECORD:"Date of Enrollment"::STRING
    END AS ENROLLMENT_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN RAW_RECORD:"Last_Flight_Date"::STRING
      WHEN 'IND_CSV' THEN RAW_RECORD:"Flight Date"::STRING
      WHEN 'USA_CSV' THEN RAW_RECORD:"FlightDate"::STRING
      WHEN 'AUS_CSV' THEN RAW_RECORD:"Date of Flight"::STRING
    END AS FLIGHT_RAW,
    CASE WHEN SOURCE_LAYOUT = 'IND_CSV'
      THEN RAW_RECORD:"Individual or Corporate"::STRING END AS ACCOUNT_TYPE_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN NULLIF(UPPER(TRIM(RAW_RECORD:"Country"::STRING)), '')
      WHEN 'IND_CSV' THEN NULLIF(UPPER(TRIM(RAW_RECORD:"Country"::STRING)), '')
      WHEN 'USA_CSV' THEN NULLIF(UPPER(TRIM(RAW_RECORD:"Country"::STRING)), '')
      WHEN 'AUS_CSV' THEN NULLIF(UPPER(TRIM(RAW_RECORD:"Country"::STRING)), '')
    END AS COUNTRY_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN RAW_RECORD:"Agent_Name"::STRING
      WHEN 'IND_CSV' THEN RAW_RECORD:"Agent_Name"::STRING
      WHEN 'USA_CSV' THEN RAW_RECORD:"Agent_Name"::STRING
      WHEN 'AUS_CSV' THEN RAW_RECORD:"Agent_Name"::STRING
    END AS AGENT_NAME_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN RAW_RECORD:"State"::STRING
      WHEN 'IND_CSV' THEN RAW_RECORD:"State"::STRING
      WHEN 'USA_CSV' THEN RAW_RECORD:"State"::STRING
      WHEN 'AUS_CSV' THEN RAW_RECORD:"State"::STRING
    END AS STATE_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN NULL
      WHEN 'IND_CSV' THEN RAW_RECORD:"Post Code"::STRING
      WHEN 'USA_CSV' THEN RAW_RECORD:"Post Code"::STRING
      WHEN 'AUS_CSV' THEN RAW_RECORD:"Post Code"::STRING
    END AS POST_CODE_RAW,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN RAW_RECORD:"Is_Active"::STRING
      WHEN 'IND_CSV' THEN RAW_RECORD:"Is_Active"::STRING
      WHEN 'USA_CSV' THEN RAW_RECORD:"Is_Active"::STRING
      WHEN 'AUS_CSV' THEN RAW_RECORD:"Is_Active"::STRING
    END AS ACTIVE_RAW
  FROM SKYPOINTS.RAW.MEMBER_LANDING r
  WHERE INGEST_BATCH_ID = $BATCH_ID::STRING
), cleaned AS (
  SELECT e.*,
    NULLIF(NULLIF(TRIM(MEMBER_ID_RAW), ''), 'NULL') AS MEMBER_ID,
    NULLIF(TRIM(MEMBER_NAME_RAW), '') AS MEMBER_NAME,
    NULLIF(NULLIF(UPPER(TRIM(TIER_RAW)), ''), 'NULL') AS TIER_CODE,
    NULLIF(NULLIF(UPPER(TRIM(ACCOUNT_TYPE_RAW)), ''), 'NULL') AS ACCOUNT_TYPE,
    NULLIF(NULLIF(UPPER(TRIM(ACTIVE_RAW)), ''), 'NULL') AS ACTIVE_TEXT,
    NULLIF(NULLIF(UPPER(TRIM(DOB_RAW)), ''), 'NULL') AS DOB_TEXT,
    NULLIF(NULLIF(UPPER(TRIM(ENROLLMENT_RAW)), ''), 'NULL') AS ENROLLMENT_TEXT,
    NULLIF(NULLIF(UPPER(TRIM(FLIGHT_RAW)), ''), 'NULL') AS FLIGHT_TEXT,
    COALESCE(NULLIF(
      CASE UPPER(TRIM(COUNTRY_RAW))
        WHEN 'INDIA' THEN 'IND' WHEN 'IND' THEN 'IND'
        WHEN 'UNITED STATES' THEN 'USA' WHEN 'US' THEN 'USA' WHEN 'USA' THEN 'USA'
        WHEN 'AUSTRALIA' THEN 'AUS' WHEN 'AU' THEN 'AUS' WHEN 'AUS' THEN 'AUS'
        WHEN 'PHIL' THEN 'PHL' WHEN 'PHILIPPINES' THEN 'PHL'
        WHEN 'CANADA' THEN 'CAN' WHEN 'CAN' THEN 'CAN'
        ELSE UPPER(TRIM(COUNTRY_RAW))
      END,
      ''), SOURCE_COUNTRY_CODE
    ) AS COUNTRY_CODE
  FROM extracted e
), parsed AS (
  SELECT c.*,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN TRY_TO_DATE(DOB_TEXT, 'MMDDYYYY')
      WHEN 'IND_CSV' THEN TRY_TO_DATE(
        CASE WHEN REGEXP_LIKE(DOB_TEXT, '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}$') THEN
          LPAD(SPLIT_PART(DOB_TEXT, '/', 1), 2, '0') || '/' ||
          LPAD(SPLIT_PART(DOB_TEXT, '/', 2), 2, '0') || '/' || SPLIT_PART(DOB_TEXT, '/', 3)
        END, 'MM/DD/YYYY')
      WHEN 'USA_CSV' THEN NULL
      WHEN 'AUS_CSV' THEN TRY_TO_DATE(DOB_TEXT, 'YYYY-MM-DD')
    END AS DATE_OF_BIRTH,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN TRY_TO_DATE(ENROLLMENT_TEXT, 'YYYYMMDD')
      WHEN 'IND_CSV' THEN TRY_TO_DATE(
        CASE WHEN REGEXP_LIKE(ENROLLMENT_TEXT, '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}$') THEN
          LPAD(SPLIT_PART(ENROLLMENT_TEXT, '/', 1), 2, '0') || '/' ||
          LPAD(SPLIT_PART(ENROLLMENT_TEXT, '/', 2), 2, '0') || '/' || SPLIT_PART(ENROLLMENT_TEXT, '/', 3)
        END, 'MM/DD/YYYY')
      WHEN 'USA_CSV' THEN TRY_TO_DATE(
        CASE
          WHEN REGEXP_LIKE(ENROLLMENT_TEXT, '^[0-9]{7}$') THEN
            LPAD(SUBSTR(ENROLLMENT_TEXT, 1, 1), 2, '0') || '/' ||
            LPAD(SUBSTR(ENROLLMENT_TEXT, 2, 2), 2, '0') || '/' || SUBSTR(ENROLLMENT_TEXT, 4, 4)
          WHEN REGEXP_LIKE(ENROLLMENT_TEXT, '^[0-9]{8}$') THEN
            LPAD(SUBSTR(ENROLLMENT_TEXT, 1, 2), 2, '0') || '/' ||
            LPAD(SUBSTR(ENROLLMENT_TEXT, 3, 2), 2, '0') || '/' || SUBSTR(ENROLLMENT_TEXT, 5, 4)
        END, 'MM/DD/YYYY')
      WHEN 'AUS_CSV' THEN TRY_TO_DATE(ENROLLMENT_TEXT, 'YYYY-MM-DD')
    END AS ENROLLMENT_DATE,
    CASE SOURCE_LAYOUT
      WHEN 'GLOBAL_PIPE' THEN TRY_TO_DATE(FLIGHT_TEXT, 'YYYYMMDD')
      WHEN 'IND_CSV' THEN TRY_TO_DATE(
        CASE WHEN REGEXP_LIKE(FLIGHT_TEXT, '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}$') THEN
          LPAD(SPLIT_PART(FLIGHT_TEXT, '/', 1), 2, '0') || '/' ||
          LPAD(SPLIT_PART(FLIGHT_TEXT, '/', 2), 2, '0') || '/' || SPLIT_PART(FLIGHT_TEXT, '/', 3)
        END, 'MM/DD/YYYY')
      WHEN 'USA_CSV' THEN TRY_TO_DATE(
        CASE
          WHEN REGEXP_LIKE(FLIGHT_TEXT, '^[0-9]{7}$') THEN
            LPAD(SUBSTR(FLIGHT_TEXT, 1, 1), 2, '0') || '/' ||
            LPAD(SUBSTR(FLIGHT_TEXT, 2, 2), 2, '0') || '/' || SUBSTR(FLIGHT_TEXT, 4, 4)
          WHEN REGEXP_LIKE(FLIGHT_TEXT, '^[0-9]{8}$') THEN
            LPAD(SUBSTR(FLIGHT_TEXT, 1, 2), 2, '0') || '/' ||
            LPAD(SUBSTR(FLIGHT_TEXT, 3, 2), 2, '0') || '/' || SUBSTR(FLIGHT_TEXT, 5, 4)
        END, 'MM/DD/YYYY')
      WHEN 'AUS_CSV' THEN TRY_TO_DATE(FLIGHT_TEXT, 'YYYY-MM-DD')
    END AS LAST_FLIGHT_DATE
  FROM cleaned c
), keyed AS (
  -- Member Name is the declared key in the assessment. Normalize case and spaces
  -- for a deterministic fallback; an authoritative crosswalk can supply the same
  -- canonical key when identity is known across source systems.
  SELECT p.*,
    COALESCE(x.GLOBAL_MEMBER_ID,
      'NAME:' || UPPER(TRIM(p.MEMBER_NAME))) AS MEMBER_KEY,
    CASE
      WHEN ACTIVE_TEXT IN ('A', 'Y', '1') THEN TRUE
      WHEN ACTIVE_TEXT IN ('I', 'N', '0') THEN FALSE
      ELSE NULL
    END AS ACTIVE_MEMBER
  FROM parsed p
  LEFT JOIN SKYPOINTS.CORE.MEMBER_ID_XREF x
    ON x.SOURCE_SYSTEM = 'MEMBER_FEED'
   AND x.SOURCE_COUNTRY_CODE = p.SOURCE_COUNTRY_CODE
   AND x.SOURCE_MEMBER_ID = p.MEMBER_ID
   AND (x.ACTIVE_FROM IS NULL OR x.ACTIVE_FROM <= CURRENT_DATE())
   AND (x.ACTIVE_TO IS NULL OR x.ACTIVE_TO >= CURRENT_DATE())
), named AS (
  SELECT k.*,
         COUNT(*) OVER (
           PARTITION BY k.SOURCE_FILE, UPPER(TRIM(k.MEMBER_NAME))
         ) AS NAME_OCCURRENCE_COUNT
  FROM keyed k
), checked AS (
  SELECT k.*,
    ARRAY_CONSTRUCT_COMPACT(
      IFF(MEMBER_ID IS NULL, 'MISSING_MEMBER_ID', NULL),
      IFF(MEMBER_ID IS NOT NULL AND LENGTH(MEMBER_ID) > 18, 'MEMBER_ID_TOO_LONG', NULL),
      IFF(MEMBER_NAME IS NULL, 'MISSING_MEMBER_NAME', NULL),
      IFF(MEMBER_NAME IS NOT NULL AND LENGTH(MEMBER_NAME) > 255, 'MEMBER_NAME_TOO_LONG', NULL),
      IFF(MEMBER_NAME IS NOT NULL AND NAME_OCCURRENCE_COUNT > 1,
          'DUPLICATE_MEMBER_NAME_IN_SOURCE_FILE', NULL),
      IFF(ENROLLMENT_TEXT IS NULL OR ENROLLMENT_DATE IS NULL, 'INVALID_OR_MISSING_ENROLLMENT_DATE', NULL),
      IFF(ENROLLMENT_DATE > CURRENT_DATE(), 'ENROLLMENT_DATE_IN_FUTURE', NULL),
      IFF(DOB_TEXT IS NOT NULL AND DATE_OF_BIRTH IS NULL, 'INVALID_DATE_OF_BIRTH', NULL),
      IFF(DATE_OF_BIRTH > CURRENT_DATE(), 'DATE_OF_BIRTH_IN_FUTURE', NULL),
      IFF(FLIGHT_TEXT IS NOT NULL AND LAST_FLIGHT_DATE IS NULL, 'INVALID_FLIGHT_DATE', NULL),
      IFF(LAST_FLIGHT_DATE > CURRENT_DATE(), 'FLIGHT_DATE_IN_FUTURE', NULL),
      IFF(LAST_FLIGHT_DATE IS NOT NULL AND ENROLLMENT_DATE IS NOT NULL
          AND LAST_FLIGHT_DATE < ENROLLMENT_DATE, 'FLIGHT_BEFORE_ENROLLMENT', NULL),
      IFF(TIER_CODE IS NOT NULL AND TIER_CODE NOT IN ('SLV', 'GLD', 'PLT'), 'UNKNOWN_TIER_CODE', NULL),
      IFF(TIER_CODE IS NOT NULL AND LENGTH(TIER_CODE) > 5, 'TIER_CODE_TOO_LONG', NULL),
      IFF(ACCOUNT_TYPE IS NOT NULL AND ACCOUNT_TYPE NOT IN ('I', 'C'), 'INVALID_ACCOUNT_TYPE', NULL),
      IFF(ACTIVE_TEXT IS NOT NULL AND ACTIVE_MEMBER IS NULL, 'INVALID_ACTIVE_FLAG', NULL),
      IFF(AGENT_NAME_RAW IS NOT NULL AND LENGTH(AGENT_NAME_RAW) > 255, 'AGENT_NAME_TOO_LONG', NULL),
      IFF(STATE_RAW IS NOT NULL AND LENGTH(STATE_RAW) > 5, 'STATE_CODE_TOO_LONG', NULL),
      IFF(POST_CODE_RAW IS NOT NULL AND NOT REGEXP_LIKE(TRIM(POST_CODE_RAW), '^[0-9]{1,5}$'), 'INVALID_POST_CODE', NULL),
      IFF(k.COUNTRY_CODE IS NULL OR LENGTH(k.COUNTRY_CODE) > 5, 'INVALID_COUNTRY_CODE', NULL),
      IFF(k.SOURCE_LAYOUT = 'GLOBAL_PIPE'
          AND COALESCE(UPPER(TRIM(k.RAW_RECORD:"Record_Type"::STRING)), '') <> 'D',
          'UNEXPECTED_RECORD_TYPE', NULL),
      IFF(NOT COALESCE(cfg.IS_ENABLED, FALSE), 'COUNTRY_TARGET_NOT_CONFIGURED', NULL)
    ) AS DQ_ERRORS
  FROM named k
  LEFT JOIN SKYPOINTS.CORE.COUNTRY_TARGET_CONFIG cfg
    ON cfg.COUNTRY_CODE = k.COUNTRY_CODE AND cfg.IS_ENABLED
)
SELECT
  INGEST_BATCH_ID,
  SOURCE_LAYOUT,
  COALESCE(MEMBER_KEY, 'INVALID:' || SOURCE_FILE || ':' || SOURCE_ROW_NUMBER::STRING),
  MEMBER_ID,
  MEMBER_NAME,
  COUNTRY_CODE,
  SOURCE_COUNTRY_CODE,
  DATE_OF_BIRTH,
  TIER_CODE,
  ENROLLMENT_DATE,
  LAST_FLIGHT_DATE,
  ACCOUNT_TYPE,
  ACTIVE_MEMBER,
  AGENT_NAME_RAW,
  STATE_RAW,
  POST_CODE_RAW,
  CASE
    WHEN DATE_OF_BIRTH IS NULL OR DATE_OF_BIRTH > CURRENT_DATE() THEN NULL
    ELSE DATEDIFF(year, DATE_OF_BIRTH, CURRENT_DATE())
         - IFF(TO_CHAR(CURRENT_DATE(), 'MMDD') < TO_CHAR(DATE_OF_BIRTH, 'MMDD'), 1, 0)
  END AS AGE,
  CASE
    WHEN LAST_FLIGHT_DATE IS NULL THEN NULL
    ELSE DATEDIFF(day, LAST_FLIGHT_DATE, CURRENT_DATE()) > 90
  END AS STALE_MEMBER,
  SOURCE_VERSION_TS AS RECORD_VERSION_TS,
  INGESTED_AT,
  SOURCE_FILE,
  SOURCE_ROW_NUMBER,
  RECORD_HASH,
  DQ_ERRORS,
  ARRAY_SIZE(DQ_ERRORS) = 0 AS IS_VALID,
  RAW_RECORD
FROM checked;

-- Persist invalid rows separately so valid rows can still proceed.
INSERT INTO SKYPOINTS.STG.MEMBER_DQ_QUARANTINE
  (INGEST_BATCH_ID, SOURCE_COUNTRY_CODE, SOURCE_LAYOUT, SOURCE_FILE, SOURCE_ROW_NUMBER, DQ_ERRORS, RAW_RECORD)
SELECT INGEST_BATCH_ID, SOURCE_COUNTRY_CODE, SOURCE_LAYOUT, SOURCE_FILE, SOURCE_ROW_NUMBER, DQ_ERRORS, RAW_RECORD
FROM SKYPOINTS.STG.MEMBER_NORMALIZED
WHERE INGEST_BATCH_ID = $BATCH_ID::STRING AND NOT IS_VALID;

-- One latest valid version per durable key from this batch. The crosswalk is what
-- allows versions from different countries to collapse to the same MEMBER_KEY.
CREATE OR REPLACE TEMPORARY TABLE BATCH_MEMBER_LATEST AS
SELECT *
FROM SKYPOINTS.STG.MEMBER_NORMALIZED
WHERE INGEST_BATCH_ID = $BATCH_ID::STRING AND IS_VALID
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY MEMBER_KEY
  ORDER BY RECORD_VERSION_TS DESC, INGESTED_AT DESC,
           SOURCE_FILE DESC, SOURCE_ROW_NUMBER DESC
) = 1;

BEGIN TRANSACTION;

MERGE INTO SKYPOINTS.CORE.MEMBER_PROFILE_CURRENT t
USING BATCH_MEMBER_LATEST s
  ON t.MEMBER_KEY = s.MEMBER_KEY
WHEN MATCHED AND s.RECORD_VERSION_TS >= t.RECORD_VERSION_TS THEN UPDATE SET
  t.MEMBER_ID = s.MEMBER_ID,
  t.MEMBER_NAME = s.MEMBER_NAME,
  t.COUNTRY_CODE = s.COUNTRY_CODE,
  t.SOURCE_COUNTRY_CODE = s.SOURCE_COUNTRY_CODE,
  t.DATE_OF_BIRTH = s.DATE_OF_BIRTH,
  t.TIER_CODE = s.TIER_CODE,
  t.ENROLLMENT_DATE = s.ENROLLMENT_DATE,
  t.LAST_FLIGHT_DATE = s.LAST_FLIGHT_DATE,
  t.ACCOUNT_TYPE = s.ACCOUNT_TYPE,
  t.ACTIVE_MEMBER = s.ACTIVE_MEMBER,
  t.AGENT_NAME = s.AGENT_NAME,
  t.STATE_CODE = s.STATE_CODE,
  t.POST_CODE = s.POST_CODE,
  t.AGE = s.AGE,
  t.STALE_MEMBER = s.STALE_MEMBER,
  t.RECORD_VERSION_TS = s.RECORD_VERSION_TS,
  t.INGESTED_AT = s.INGESTED_AT,
  t.SOURCE_FILE = s.SOURCE_FILE,
  t.SOURCE_ROW_NUMBER = s.SOURCE_ROW_NUMBER,
  t.RECORD_HASH = s.RECORD_HASH
WHEN NOT MATCHED THEN INSERT (
  MEMBER_KEY, MEMBER_ID, MEMBER_NAME, COUNTRY_CODE, SOURCE_COUNTRY_CODE,
  DATE_OF_BIRTH, TIER_CODE, ENROLLMENT_DATE, LAST_FLIGHT_DATE, ACCOUNT_TYPE,
  ACTIVE_MEMBER, AGENT_NAME, STATE_CODE, POST_CODE, AGE, STALE_MEMBER,
  RECORD_VERSION_TS, INGESTED_AT, SOURCE_FILE, SOURCE_ROW_NUMBER, RECORD_HASH
) VALUES (
  s.MEMBER_KEY, s.MEMBER_ID, s.MEMBER_NAME, s.COUNTRY_CODE, s.SOURCE_COUNTRY_CODE,
  s.DATE_OF_BIRTH, s.TIER_CODE, s.ENROLLMENT_DATE, s.LAST_FLIGHT_DATE, s.ACCOUNT_TYPE,
  s.ACTIVE_MEMBER, s.AGENT_NAME, s.STATE_CODE, s.POST_CODE, s.AGE, s.STALE_MEMBER,
  s.RECORD_VERSION_TS, s.INGESTED_AT, s.SOURCE_FILE, s.SOURCE_ROW_NUMBER, s.RECORD_HASH
);

-- Delete touched keys from all country tables, then reinsert their single current
-- row into the destination table. This removes stale copies on country movement.
DELETE FROM SKYPOINTS.CORE.MEMBERS_IND t
USING BATCH_MEMBER_LATEST s WHERE t.MEMBER_KEY = s.MEMBER_KEY;
DELETE FROM SKYPOINTS.CORE.MEMBERS_USA t
USING BATCH_MEMBER_LATEST s WHERE t.MEMBER_KEY = s.MEMBER_KEY;
DELETE FROM SKYPOINTS.CORE.MEMBERS_AUS t
USING BATCH_MEMBER_LATEST s WHERE t.MEMBER_KEY = s.MEMBER_KEY;
DELETE FROM SKYPOINTS.CORE.MEMBERS_PHL t
USING BATCH_MEMBER_LATEST s WHERE t.MEMBER_KEY = s.MEMBER_KEY;
DELETE FROM SKYPOINTS.CORE.MEMBERS_CAN t
USING BATCH_MEMBER_LATEST s WHERE t.MEMBER_KEY = s.MEMBER_KEY;

