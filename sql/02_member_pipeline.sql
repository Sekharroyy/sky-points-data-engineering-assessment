-- Batch summary for orchestration. Treat any invalid row or count mismatch as a
-- review condition; quarantine does not block other valid members in the batch.
SELECT INGEST_BATCH_ID, SOURCE_COUNTRY_CODE, IS_VALID, COUNT(*) AS ROW_COUNT
FROM SKYPOINTS.STG.MEMBER_NORMALIZED
WHERE INGEST_BATCH_ID = $BATCH_ID::STRING
GROUP BY INGEST_BATCH_ID, SOURCE_COUNTRY_CODE, IS_VALID
ORDER BY SOURCE_COUNTRY_CODE, IS_VALID;
